#!/usr/bin/env node
/**
 * Concatenate each phase's migrations into one file for the Supabase SQL editor.
 *
 * The Supabase CLI (`supabase db push`) is the better route because it records
 * which migrations have run. These files exist for the case where the CLI is not
 * installed and somebody is pasting SQL into a browser: seventeen separate pastes
 * in the right order is seventeen chances to get the order wrong, and these
 * migrations are NOT idempotent -- re-running one fails on an existing type or
 * table.
 *
 * WHY THIS IS DRIVEN BY A LIST OF PHASES RATHER THAN ONE PREFIX
 *
 * It used to hardcode `20260201`, so it generated the Phase 2 bundle and
 * nothing else. That was fine until Phase 3 landed, and then it was worse
 * than useless: CI's "Deploy SQL is up to date" step went on passing while
 * nine migrations had no deploy artifact at all. A check that reports
 * success over a third of the schema it cannot see is not a check -- it is a
 * false assurance, and somebody deploying from this repo would have read it
 * as coverage.
 *
 * Adding a phase now means adding a line to PHASES. Forgetting to is caught,
 * because every migration must belong to exactly one phase or this exits 1.
 *
 * The seeds are deliberately NOT included. They carry `on conflict` clauses
 * and are safe to re-run, so they are applied separately and re-applied
 * whenever content changes. Bundling them here would tempt somebody to paste
 * the whole thing twice.
 *
 *   node scripts/build-deploy-sql.mjs
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join } from 'node:path'

// --check writes nothing and fails if a generated file is out of date. A
// generated file that has silently drifted from its source is worse than no
// generated file: somebody pastes it into production believing it matches the
// migrations, and it does not.
const CHECK_ONLY = process.argv.includes('--check')

const ROOT = join(dirname(new URL(import.meta.url).pathname), '..')
const MIGRATIONS = join(ROOT, 'supabase', 'migrations')
const DEPLOY = join(ROOT, 'supabase', 'deploy')
const STEPS = join(DEPLOY, 'steps')

// Phase 1 has no bundle: it predates this script and is already applied
// everywhere it needs to be. It is listed so the "every migration belongs to
// a phase" check below can account for its files rather than reporting them
// as orphans.
const PHASES = [
  { prefix: '20260101', number: 1, bundle: false, requires: 'an empty database' },
  { prefix: '20260201', number: 2, bundle: true, requires: 'the Phase 1 schema' },
  { prefix: '20260301', number: 3, bundle: true, requires: 'the Phase 2 schema' },
]

const all = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith('.sql'))
  .sort()

const orphans = all.filter((f) => !PHASES.some((p) => f.startsWith(p.prefix)))
if (orphans.length > 0) {
  console.error(
    `These migrations belong to no phase in build-deploy-sql.mjs:\n` +
      orphans.map((f) => `  - ${f}`).join('\n') +
      `\n\nAdd the phase to PHASES, or they will deploy with no bundle.`,
  )
  process.exit(1)
}

for (const phase of PHASES) {
  phase.files = all.filter((f) => f.startsWith(phase.prefix))
  if (phase.files.length === 0) {
    console.error(`No migrations matching ${phase.prefix}* in ${MIGRATIONS}`)
    process.exit(1)
  }
}

// Steps are numbered across every bundled phase in one sequence, because the
// instruction that matters is "run these in order" and two directories each
// starting at 01 invites somebody to run 01 twice.
const bundled = PHASES.filter((p) => p.bundle)
const stepTotal = bundled.reduce((n, p) => n + p.files.length, 0)

// A phase that adds an enum value cannot be one transaction.
//
// PostgreSQL rejects "unsafe use of new value" when a new enum label is used
// in the transaction that added it. Splitting the label into its own
// migration fixes every consumer that runs one migration per transaction --
// but NOT a bundle that wraps a whole phase in one, because there the add and
// the use are still together.
//
// So the bundle shape is chosen by what the phase contains rather than fixed:
// atomic where that is achievable, one transaction per migration where it is
// not, and the header says which and what a failure leaves behind. Claiming
// "a failure leaves the database exactly as it was" over a file that cannot
// deliver it would be the worst of the three options.
function addsEnumValue(body) {
  const code = body
    .split('\n')
    .filter((line) => !line.trimStart().startsWith('--'))
    .join('\n')
  return /alter\s+type\b[\s\S]*?\badd\s+value\b/i.test(code)
}

function bundleFor(phase) {
  const bodies = phase.files.map((f) =>
    readFileSync(join(MIGRATIONS, f), 'utf8').trim(),
  )
  const atomic = !bodies.some(addsEnumValue)

  const parts = [
    `-- Texas Exam Prep — Phase ${phase.number} schema`,
    `--`,
    `-- Generated by scripts/build-deploy-sql.mjs. Do not edit by hand; edit the`,
    `-- migrations in supabase/migrations/ and regenerate.`,
    `--`,
    `-- Run this ONCE against a project that already has ${phase.requires}.`,
    `-- These statements are not idempotent: running them twice fails on an`,
    `-- existing type or table, which is the correct behaviour, not a bug.`,
    `--`,
    ...(atomic
      ? [
          `-- Wrapped in a single transaction, so a failure anywhere leaves the`,
          `-- database exactly as it was rather than half-migrated.`,
        ]
      : [
          `-- ONE TRANSACTION PER MIGRATION, NOT ONE FOR THE FILE.`,
          `--`,
          `-- This phase adds a value to an enum type, and PostgreSQL will not`,
          `-- let a new enum value be used in the transaction that added it. The`,
          `-- whole file therefore cannot be atomic.`,
          `--`,
          `-- So a failure part-way leaves the migrations BEFORE it applied and`,
          `-- the rest not. That is recoverable but it is not nothing: note`,
          `-- which migration failed, fix the cause, and resume from that one`,
          `-- using supabase/deploy/steps/ rather than re-running this file.`,
        ]),
    ...phase.files.map((f) => `--   - ${f}`),
    ``,
  ]

  if (atomic) parts.push(`begin;`, ``)

  phase.files.forEach((file, i) => {
    parts.push(
      `-- ${'-'.repeat(74)}`,
      `-- ${file}`,
      `-- ${'-'.repeat(74)}`,
      ``,
    )
    if (!atomic) parts.push(`begin;`, ``)
    parts.push(bodies[i], ``)
    if (!atomic) parts.push(`commit;`, ``)
  })

  if (atomic) parts.push(`commit;`, ``)
  return parts.join('\n')
}

// The same migrations again, one file each, every one wrapped in its own
// transaction.
//
// Why both shapes exist: the single file is one paste and one transaction,
// which is what you want when it works. When it does NOT work, a 970-line
// paste into a browser SQL editor is the hardest possible thing to diagnose --
// a truncated paste and a broken statement look identical, and the error
// points at a line that reads fine in the repository. Small files cannot
// truncate the same way, and whichever one fails names the migration.
//
// Each step is its own transaction, so a failure leaves that step's database
// exactly as it was. The steps must still be run IN ORDER; a later one
// references what an earlier one created.
function buildSteps() {
  const out = []
  let index = 0
  for (const phase of bundled) {
    for (const file of phase.files) {
      index += 1
      const n = String(index).padStart(2, '0')
      const name = file.replace(/^\d+_/, '').replace(/\.sql$/, '')
      const body = [
        `-- Texas Exam Prep — deploy step ${n} of ${stepTotal} (Phase ${phase.number})`,
        `--`,
        `-- ${file}`,
        `--`,
        `-- Generated by scripts/build-deploy-sql.mjs. Do not edit by hand.`,
        `--`,
        `-- Run the steps IN ORDER. This one is a single transaction, so if it`,
        `-- fails nothing in it is applied and you can fix the cause and re-run`,
        `-- this step alone. Steps already applied must NOT be re-run: they are`,
        `-- not idempotent and will fail on an existing type or table.`,
        ``,
        `begin;`,
        ``,
        readFileSync(join(MIGRATIONS, file), 'utf8').trim(),
        ``,
        `commit;`,
        ``,
      ].join('\n')
      out.push({ path: join(STEPS, `${n}-${name}.sql`), body })
    }
  }
  return out
}

const artifacts = [
  ...bundled.map((phase) => ({
    path: join(DEPLOY, `phase-${phase.number}-schema.sql`),
    body: bundleFor(phase),
  })),
  ...buildSteps(),
]

// A step file left behind by a rename would be run in sequence by anybody
// following the directory listing, so a stale one is not clutter -- it is a
// migration applied twice.
const expected = new Set(artifacts.map((a) => a.path))
const stale = existsSync(STEPS)
  ? readdirSync(STEPS)
      .filter((f) => f.endsWith('.sql'))
      .map((f) => join(STEPS, f))
      .filter((p) => !expected.has(p))
  : []

if (CHECK_ONLY) {
  for (const artifact of artifacts) {
    const rel = artifact.path.slice(ROOT.length + 1)
    if (!existsSync(artifact.path)) {
      console.error(`${rel} is missing. Run: node scripts/build-deploy-sql.mjs`)
      process.exit(1)
    }
    if (readFileSync(artifact.path, 'utf8') !== artifact.body) {
      console.error(
        `${rel} is out of date with supabase/migrations/.\n` +
          `Run: node scripts/build-deploy-sql.mjs`,
      )
      process.exit(1)
    }
  }
  if (stale.length > 0) {
    console.error(
      `Step files with no matching migration:\n` +
        stale.map((p) => `  - ${p.slice(ROOT.length + 1)}`).join('\n') +
        `\n\nRun: node scripts/build-deploy-sql.mjs`,
    )
    process.exit(1)
  }
  console.log(
    `${bundled.length} phase bundle(s) and ${stepTotal} step file(s): up to date`,
  )
} else {
  mkdirSync(STEPS, { recursive: true })
  for (const artifact of artifacts) writeFileSync(artifact.path, artifact.body)
  for (const phase of bundled) {
    console.log(
      `supabase/deploy/phase-${phase.number}-schema.sql: ` +
        `${phase.files.length} migration(s)`,
    )
  }
  console.log(`supabase/deploy/steps/: ${stepTotal} step file(s)`)
  if (stale.length > 0) {
    console.log(
      `\nStale step files, delete them:\n` +
        stale.map((p) => `  - ${p.slice(ROOT.length + 1)}`).join('\n'),
    )
  }
}
